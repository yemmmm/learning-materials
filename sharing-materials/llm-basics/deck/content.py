SLIDES = []


def panel(title, text, kind=""):
    return f'<section class="panel {kind}"><h3>{title}</h3>{text}</section>'


def p(text, cls=""):
    return f'<p class="{cls}">{text}</p>'


def grid(*items, cls="two"):
    return f'<div class="grid {cls}">' + "".join(items) + "</div>"


def call(text, cls=""):
    return f'<div class="callout {cls}">{text}</div>'


def flow(*items):
    return '<div class="flow">' + '<span class="arrow">→</span>'.join(f'<div class="node">{item}</div>' for item in items) + "</div>"


def table(headers, rows, cls=""):
    return f'<table class="{cls}"><thead><tr>' + "".join(f"<th>{v}</th>" for v in headers) + "</tr></thead><tbody>" + "".join("<tr>" + "".join(f"<td>{v}</td>" for v in row) + "</tr>" for row in rows) + "</tbody></table>"


def choices(attribute, labels, selected=0):
    return '<div class="choices">' + "".join(f'<button class="choice {"selected" if i == selected else ""}" data-{attribute}="{i}" aria-pressed="{str(i == selected).lower()}">{label}</button>' for i, label in enumerate(labels)) + "</div>"


